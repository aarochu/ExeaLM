def planned_tokens(mix=MIX):
    """Billions of tokens the mix adds up to (passes included)."""
    tot = 0.0
    for v in mix.values():
        parts = v.split()
        tot += float(parts[0]) * (int(parts[1][1:]) if len(parts) > 1 else 1)
    return tot


